// Fluxo real no navegador: login (código de dev) → cadastro → Passport fechado → aberto → páginas.
import { webkit, chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3530";
const engine = process.argv[3] ?? "webkit";
const out = ".data/shots";
const browser = await (engine === "webkit" ? webkit : chromium).launch();
const ctx = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: engine !== "webkit" ? true : undefined, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(String(e)));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const email = `smoke-${Date.now()}@teste.local`;
await page.goto(`${base}/calculadora`, { waitUntil: "networkidle" });
await page.waitForTimeout(800);
await page.fill("input[type=date] >> nth=0", "1990-06-10");
await page.getByText("Masculino").click();
await page.fill("input[inputmode=numeric]", "3:12:30");
await page.fill("input[type=date] >> nth=1", "2026-09-20");
await page.getByRole("button", { name: "Calcular meu índice" }).click();
await page.getByText("Índice oficial da faixa").waitFor();
await page.screenshot({ path: `${out}/lab-result-390.png`, fullPage: false });
await page.getByRole("button", { name: /Criar meu Boston Passport/ }).click();
await page.waitForURL(/cadastro/);
await page.fill("#email", email);
await page.getByRole("button", { name: "Receber código" }).click();
const code = (await page.getByTestId("dev-code").textContent()).match(/\d{6}/)[0];
await page.fill("#code", code);
await page.getByRole("button", { name: "Entrar" }).click();
await page.waitForURL(/cadastro/);
await page.fill("#fullName", "Marina Costa Ribeiro");
await page.fill("#phone", `(61) 9${String(Date.now()).slice(-8)}`);
await page.fill("#cep", "70150-900");
await page.locator("#cep-hint").filter({ hasText: /Achamos|Não achamos|não respondeu/ }).waitFor();
await page.fill("#city", "Brasília");
await page.selectOption("#uf", "DF");
await page.screenshot({ path: `${out}/cadastro-1-390.png`, fullPage: true });
await page.getByRole("button", { name: "Continuar" }).click();
await page.getByText("Sim, atualmente").click();
await page.fill("#coachName", "Professor Exemplo");
await page.getByRole("button", { name: "Continuar" }).click();
await page.locator("label[for=acceptTerms]").click();
await page.getByRole("button", { name: "Emitir meu Boston Passport" }).click();
await page.waitForURL(/passport/);
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/passport-closed-390.png` });
await page.getByRole("button", { name: "Abrir meu passaporte" }).last().click();
await page.waitForTimeout(1200);
await page.screenshot({ path: `${out}/passport-open-390.png` });
for (let i = 1; i < 5; i++) {
  await page.getByRole("button", { name: "Próxima página" }).click();
  await page.waitForTimeout(700);
  await page.screenshot({ path: `${out}/passport-page${i + 1}-390.png` });
}
const overflow = await page.evaluate(() => document.documentElement.scrollWidth - window.innerWidth);
console.log(JSON.stringify({ email, overflow, errors: errors.slice(0, 8) }));
await browser.close();
